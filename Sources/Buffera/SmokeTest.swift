func runSmokeTest() throws {
    let pasteboard = NSPasteboard.withUniqueName()
    defer { pasteboard.releaseGlobally() }
    let service = ClipboardService(pasteboard: pasteboard)
    let payload = ClipPayload(items: [
        [Representation(type: NSPasteboard.PasteboardType.string.rawValue, data: Data("Проверка буфера".utf8)),
         Representation(type: "app.buffera.custom", data: Data([0, 1, 2, 255]))],
        [Representation(type: NSPasteboard.PasteboardType.fileURL.rawValue, data: Data("file:///tmp/example.txt".utf8))]
    ])
    try service.restore(payload)
    guard try service.capture()?.payload == payload else { throw HistoryError.invalidPayload }
    var captured = false
    service.onCapture = { _ in captured = true }
    service.poll()
    guard !captured else { throw HistoryError.database("Own write was captured") }
    pasteboard.clearContents(); pasteboard.setString("Новое копирование", forType: .string)
    service.poll()
    guard captured else { throw HistoryError.database("External write was not captured") }
    let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8,
                                 samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    let imagePayload = ClipPayload(items: [[Representation(type: NSPasteboard.PasteboardType.tiff.rawValue, data: bitmap.tiffRepresentation!)]])
    guard let (png, ext) = ClipboardService.imageData(imagePayload), ext == "png", NSBitmapImageRep(data: png)?.pixelsWide == 2 else { throw ClipboardFailure.noImage }
    let provider = SecretPromiseFixture()
    let promised = NSPasteboardItem()
    promised.setDataProvider(provider, forTypes: [.string])
    promised.setString("", forType: .init("org.nspasteboard.ConcealedType"))
    pasteboard.clearContents()
    guard pasteboard.writeObjects([promised]), try service.capture() == nil, provider.reads == 0 else {
        throw HistoryError.database("Skip mode requested promised secret bytes")
    }
    for marker in ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"] {
        let sensitive = NSPasteboardItem(); sensitive.setString("smoke-secret-fixture", forType: .string)
        sensitive.setString("", forType: .init(marker))
        let companion = NSPasteboardItem(); companion.setString("smoke-second-value", forType: .string)
        pasteboard.clearContents()
        guard pasteboard.writeObjects([sensitive, companion]) else { throw ClipboardFailure.writeFailed }
        service.savesConcealed = false
        guard try service.capture() == nil else { throw HistoryError.database("Secret captured in skip mode") }
        service.savesConcealed = true
        guard let clip = try service.capture(),
              clip.isConcealed, clip.title == "Скрытая запись", clip.text.isEmpty,
              ClipboardService.revealedText(clip.payload) == "smoke-secret-fixture\nsmoke-second-value" else {
            throw HistoryError.database("Concealed group was not retained and masked")
        }
        try service.restore(clip.payload)
        guard let restored = try service.capture(), restored.isConcealed, restored.payload == clip.payload,
              restored.title == "Скрытая запись", restored.text.isEmpty else {
            throw HistoryError.database("Concealed payload or masking did not survive restore")
        }
    }
    for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        let transient = NSPasteboardItem(); transient.setString("Generated fixture", forType: .string)
        transient.setString("", forType: .init(marker))
        pasteboard.clearContents()
        guard pasteboard.writeObjects([transient]), try service.capture() == nil else {
            throw HistoryError.database("Ordinary transient or generated entry was captured")
        }
        let concealedTransient = NSPasteboardItem(); concealedTransient.setString("smoke-secret-fixture", forType: .string)
        concealedTransient.setString("", forType: .init(marker))
        concealedTransient.setString("", forType: .init("org.nspasteboard.ConcealedType"))
        pasteboard.clearContents()
        guard pasteboard.writeObjects([concealedTransient]), let clip = try service.capture(),
              clip.isConcealed, clip.title == "Скрытая запись", clip.text.isEmpty else {
            throw HistoryError.database("Concealed entry did not take precedence over generated markers")
        }
    }
    let richText = NSAttributedString(string: "Rich text fixture")
    let rtf = try richText.data(from: NSRange(location: 0, length: richText.length),
                               documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
    let richPayload = ClipPayload(items: [[Representation(type: NSPasteboard.PasteboardType.rtf.rawValue, data: rtf)]])
    guard ClipboardService.revealedText(richPayload) == "Rich text fixture",
          ClipboardService.revealedText(imagePayload) == nil else {
        throw HistoryError.database("Explicit text reveal did not respect available representations")
    }
    let sourceItem = NSPasteboardItem(); sourceItem.setString("Source fixture", forType: .string)
    sourceItem.setString("com.apple.finder", forType: .init("org.nspasteboard.source"))
    pasteboard.clearContents()
    guard pasteboard.writeObjects([sourceItem]), let sourced = try service.capture(), !sourced.isConcealed,
          !sourced.payload.items.joined().contains(where: { $0.type == "org.nspasteboard.source" }) else {
        throw HistoryError.database("Clipboard source bookkeeping leaked into the restored payload")
    }
    try runCaptureOriginAndSessionChecks()
    try runPreviewSmokeChecks()
    try runPhotoFilePreviewChecks()
}

private func runPhotoFilePreviewChecks() throws {
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: directory) }
    let url = directory.appendingPathComponent("Фото с пробелами.jpeg")
    guard let context = CGContext(data: nil, width: 1_200, height: 800, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue),
          let image = context.makeImage() else { throw ClipboardFailure.noImage }
    let data = NSMutableData()
    guard let destination = CGImageDestinationCreateWithData(data, "public.jpeg" as CFString, 1, nil) else {
        throw ClipboardFailure.noImage
    }
    CGImageDestinationAddImage(destination, image, [kCGImagePropertyOrientation: 6] as CFDictionary)
    guard CGImageDestinationFinalize(destination) else { throw ClipboardFailure.noImage }
    try (data as Data).write(to: url)
    let file = Representation(type: NSPasteboard.PasteboardType.fileURL.rawValue, data: Data(url.absoluteString.utf8))
    let jpeg = Representation(type: "public.jpeg", data: data as Data)
    let photos = ClipPayload(items: [[
        Representation(type: "com.apple.photos.object-reference.asset", data: Data([1, 2, 3])), jpeg, file
    ]])
    let pasteboard = NSPasteboard.withUniqueName()
    defer { pasteboard.releaseGlobally() }
    let service = ClipboardService(pasteboard: pasteboard, frontmostApplicationName: { "Photos" })
    try service.restore(photos)
    guard let captured = try service.capture(), captured.kind == .file,
          captured.payload == photos, captured.title == url.lastPathComponent,
          captured.text == url.path, captured.source == "Photos",
          let thumbnail = ClipboardService.thumbnail(captured.payload),
          thumbnail.size.height == 320, thumbnail.size.width < thumbnail.size.height,
          case .image(let preview) = ClipPreviewContent.decode(captured.payload, kind: captured.kind),
          preview.size.height == 1_200, preview.size.width == 800 else {
        throw HistoryError.database("Photos JPEG/file capture lost its formats, orientation or image previews")
    }
    let fileOnly = ClipPayload(items: [[file]])
    guard ClipboardService.thumbnail(fileOnly) == nil,
          case .image = ClipPreviewContent.decode(fileOnly, kind: .file) else {
        throw HistoryError.database("A local image file without embedded pixels has no preview")
    }
    let group = ClipPayload(items: [photos.items[0], [file]])
    guard ClipboardService.thumbnail(group) == nil,
          case .text(let paths) = ClipPreviewContent.decode(group, kind: .file),
          paths == [url.path, url.path].joined(separator: "\n\n") else {
        throw HistoryError.database("An image preview hid other files in a selection")
    }
    try FileManager.default.removeItem(at: url)
    guard ClipboardService.thumbnail(photos) != nil,
          case .image = ClipPreviewContent.decode(photos, kind: .file),
          ClipboardService.thumbnail(fileOnly) == nil,
          case .text(let path) = ClipPreviewContent.decode(fileOnly, kind: .file), path == url.path else {
        throw HistoryError.database("Removed image files did not use embedded bytes or fall back to their paths")
    }
    let corrupt = Representation(type: "public.jpeg", data: Data([0, 1, 2]))
    guard ClipboardService.thumbnail(ClipPayload(items: [[corrupt, file]])) == nil,
          ClipboardService.thumbnail(ClipPayload(items: [[corrupt, jpeg, file]])) != nil,
          ClipboardService.thumbnail(ClipPayload(items: [[Representation(type: "public.file-url",
              data: Data("https://example.invalid/photo.jpeg".utf8))]])) == nil else {
        throw HistoryError.database("Image preview mishandled corrupt alternatives or nonlocal file URLs")
    }
    print("Photos JPEG/file preview checks passed")
}

private func runCaptureOriginAndSessionChecks() throws {
    let pasteboard = NSPasteboard.withUniqueName()
    defer { pasteboard.releaseGlobally() }
    let service = ClipboardService(pasteboard: pasteboard, frontmostApplicationName: { "Foreground Fixture" })
    func write(_ text: String, markers: [String: String] = [:]) throws {
        let item = NSPasteboardItem(); item.setString(text, forType: .string)
        for (type, value) in markers { item.setString(value, forType: .init(type)) }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else { throw ClipboardFailure.writeFailed }
    }
    try write("Local fixture")
    guard let local = try service.capture(), !local.isRemote, local.source == "Foreground Fixture" else {
        throw HistoryError.database("Ordinary capture lost its foreground source fallback")
    }
    for source in ["", "invalid source", "local.nonexistent-fixture"] {
        try write("Unknown source", markers: ["org.nspasteboard.source": source])
        guard try service.capture()?.source == "" else {
            throw HistoryError.database("Explicit unknown source was attributed to the foreground app")
        }
    }
    service.savesConcealed = true
    for concealed in [false, true] {
        var markers = ["com.apple.is-remote-clipboard": "", "org.nspasteboard.source": "com.apple.finder"]
        if concealed { markers["org.nspasteboard.ConcealedType"] = "" }
        try write("Remote fixture", markers: markers)
        guard let clip = try service.capture(), clip.isRemote, clip.source.isEmpty,
              clip.isConcealed == concealed,
              !clip.payload.items.joined().contains(where: { markers.keys.contains($0.type) && $0.type != "org.nspasteboard.ConcealedType" }) else {
            throw HistoryError.database("Remote origin or concealed metadata was lost or attributed to a Mac app")
        }
        try service.restore(clip.payload)
        guard let restored = try service.capture(), !restored.isRemote, restored.isConcealed == concealed else {
            throw HistoryError.database("Restored payload incorrectly retained its remote transport marker")
        }
    }
    let systemService = ClipboardService(pasteboard: pasteboard, frontmostApplicationName: { "loginwindow" })
    try write("System source fixture")
    guard try systemService.capture()?.source == "" else { throw HistoryError.database("System process was used as a clipboard app") }

    var allowed = true
    var captures = 0
    service.captureIsAllowed = { allowed }
    service.onCapture = { _ in captures += 1 }
    service.discardPendingChanges()
    allowed = false
    try write("During lock")
    service.poll()
    allowed = true
    service.poll()
    guard captures == 0 else { throw HistoryError.database("Locked clipboard was captured after polling resumed") }
    try write("New copy after unlock")
    service.poll()
    guard captures == 1 else { throw HistoryError.database("New copy after unlock was not captured") }
    allowed = false; service.discardPendingChanges()
    try write("Lock interval without poll")
    allowed = true; service.discardPendingChanges()
    service.poll()
    guard captures == 1 else { throw HistoryError.database("A lock/unlock between polls replayed pending data") }
    service.paused = true
    try write("Manual pause during unlock")
    allowed = false; service.discardPendingChanges()
    allowed = true; service.discardPendingChanges()
    service.poll()
    guard captures == 1, service.paused else { throw HistoryError.database("Unlock bypassed manual pause") }
    service.paused = false
    var permissionChecks = 0
    service.captureIsAllowed = { permissionChecks += 1; return permissionChecks == 1 }
    try write("Session locks during read")
    service.poll()
    guard captures == 1 else { throw HistoryError.database("Session was not rechecked after reading clipboard contents") }
    print("Capture origin and session checks passed")
}

private func runPreviewSmokeChecks() throws {
    func payload(_ type: NSPasteboard.PasteboardType, _ data: Data) -> ClipPayload {
        ClipPayload(items: [[Representation(type: type.rawValue, data: data)]])
    }
    let original = "Первая строка\nВторая строка 🐈"
    guard case .text(let text) = ClipPreviewContent.decode(payload(.string, Data(original.utf8)), kind: .text),
          text == original else {
        throw HistoryError.database("Preview changed Unicode text or line breaks")
    }
    let longText = String(repeating: "ж", count: 500_001)
    let truncationNotice = L10n.text("\n\n— Показаны первые 500 000 символов. Копируется запись целиком. —")
    guard case .text(let truncated) = ClipPreviewContent.decode(payload(.string, Data(longText.utf8)), kind: .text),
          truncated == String(repeating: "ж", count: 500_000) + truncationNotice else {
        throw HistoryError.database("Preview did not limit text with a truncation notice")
    }
    let path = "/tmp/проверка фото.png"
    let fileURL = URL(fileURLWithPath: path).absoluteString
    guard case .text(let fileText) = ClipPreviewContent.decode(payload(.fileURL, Data(fileURL.utf8)), kind: .file),
          fileText == path else {
        throw HistoryError.database("Preview did not decode a file URL to a readable path")
    }
    guard case .unavailable = ClipPreviewContent.decode(payload(.fileURL, Data("https://example.invalid/".utf8)), kind: .file) else {
        throw HistoryError.database("Preview accepted a nonfile URL as a file path")
    }
    guard case .unavailable = ClipPreviewContent.decode(payload(.png, Data([0, 1, 2])), kind: .image) else {
        throw HistoryError.database("Preview did not handle a corrupt image")
    }
    guard let context = CGContext(data: nil, width: 3_000, height: 2_000, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue),
          let image = context.makeImage() else {
        throw HistoryError.database("Could not create preview image fixture")
    }
    let data = NSMutableData()
    guard let destination = CGImageDestinationCreateWithData(data, "public.png" as CFString, 1, nil) else {
        throw HistoryError.database("Could not encode preview image fixture")
    }
    CGImageDestinationAddImage(destination, image, nil)
    guard CGImageDestinationFinalize(destination),
          case .image(let preview) = ClipPreviewContent.decode(payload(.png, data as Data), kind: .image),
          preview.size.width > 0, preview.size.height > 0,
          preview.size.width <= 1_600, preview.size.height <= 1_600,
          abs(preview.size.width / preview.size.height - 1.5) < 0.01 else {
        throw HistoryError.database("Preview did not downsample an image while preserving its proportions")
    }
    let binary = payload(.init("synthetic.binary"), Data([0, 1, 2]))
    guard case .text(let summary) = ClipPreviewContent.decode(binary, kind: .other),
          summary.contains("synthetic.binary"), !summary.contains("\u{0}") else {
        throw HistoryError.database("Preview did not summarize binary formats without displaying raw data")
    }
}

private final class SecretPromiseFixture: NSObject, NSPasteboardItemDataProvider {
    var reads = 0
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        reads += 1
        item.setString("promised-secret-fixture", forType: type)
    }
}
