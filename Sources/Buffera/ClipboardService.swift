import AppKit
import BufferaLocalization
import BufferaCore
import ImageIO

struct CapturedClip {
    let payload: ClipPayload
    let kind: ClipKind
    let title: String
    let text: String
    let source: String
    let isConcealed: Bool
    let isRemote: Bool
}

enum ClipboardFailure: LocalizedError {
    case tooLarge, unreadable, writeFailed, noImage
    var errorDescription: String? {
        switch self {
        case .tooLarge: return L10n.text("Элемент больше 64 МБ: он остался в буфере, но не сохранён в историю.")
        case .unreadable: return L10n.text("Некоторые данные буфера недоступны. Элемент не сохранён, чтобы не потерять его форматы.")
        case .writeFailed: return L10n.text("Не удалось записать выбранный элемент в буфер обмена.")
        case .noImage: return L10n.text("Не удалось преобразовать картинку в файл.")
        }
    }
}

final class ClipboardService {
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private let frontmostApplicationName: () -> String
    private var captureWasAllowed = true
    var onCapture: ((CapturedClip) -> Void)?
    var onError: ((Error) -> Void)?
    var captureIsAllowed: () -> Bool = { true }
    var paused = false
    // Confidential entries are retained by user choice, with no plaintext summary.
    private let concealed = Set(["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"])
    private let ignored = Set(["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
    private let bookkeeping = Set(["org.nspasteboard.source", "com.apple.is-remote-clipboard"])

    init(pasteboard: NSPasteboard = .general,
         frontmostApplicationName: @escaping () -> String = { NSWorkspace.shared.frontmostApplication?.localizedName ?? "" }) {
        self.pasteboard = pasteboard
        self.frontmostApplicationName = frontmostApplicationName
        lastChange = pasteboard.changeCount
    }

    func start() {
        timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }

    func poll() {
        let allowed = captureIsAllowed()
        let change = pasteboard.changeCount
        guard allowed, captureWasAllowed else {
            lastChange = change; captureWasAllowed = allowed
            return
        }
        guard change != lastChange else { return }
        lastChange = change
        guard !paused else { return }
        do {
            let clip = try capture()
            // Reading a promised remote representation may take time. Recheck
            // the session before handing its contents to the storage queue.
            guard captureIsAllowed() else { discardPendingChanges(); return }
            if let clip, pasteboard.changeCount == change { onCapture?(clip) }
        } catch { onError?(error) }
    }

    func discardPendingChanges() {
        lastChange = pasteboard.changeCount
        captureWasAllowed = captureIsAllowed()
    }

    func capture() throws -> CapturedClip? {
        guard let originals = pasteboard.pasteboardItems, !originals.isEmpty else { return nil }
        let rawTypes = Set(originals.flatMap { $0.types.map(\.rawValue) })
        let isConcealed = !rawTypes.isDisjoint(with: concealed)
        let isRemote = rawTypes.contains("com.apple.is-remote-clipboard")
        if !isConcealed && !rawTypes.isDisjoint(with: ignored) { return nil }
        var total = 0
        var items: [[Representation]] = []
        for original in originals {
            var representations: [Representation] = []
            for type in original.types where !bookkeeping.contains(type.rawValue) {
                guard let data = original.data(forType: type) else { throw ClipboardFailure.unreadable }
                total += data.count
                guard total <= 64 * 1024 * 1024 else { throw ClipboardFailure.tooLarge }
                representations.append(Representation(type: type.rawValue, data: data))
            }
            guard !representations.isEmpty else { throw ClipboardFailure.unreadable }
            items.append(representations)
        }
        let payload = ClipPayload(items: items)
        let types = Set(originals.flatMap(\.types))
        let source = isRemote ? "" : sourceApplication(for: originals)
        if isConcealed {
            let kind: ClipKind
            if types.contains(.fileURL) { kind = .file }
            else if types.contains(.png) || types.contains(.tiff) { kind = .image }
            else if types.contains(.string) || types.contains(.rtf) { kind = .text }
            else { kind = .other }
            return CapturedClip(payload: payload, kind: kind, title: "Скрытая запись", text: "",
                                source: source, isConcealed: true, isRemote: isRemote)
        }
        let fileURLs = originals.compactMap { $0.string(forType: .fileURL).flatMap(URL.init(string:)) }
        var text = originals.compactMap { $0.string(forType: .string) }.joined(separator: "\n")
        if text.isEmpty, let rtf = originals.first?.data(forType: .rtf) {
            text = (try? NSAttributedString(data: rtf, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil).string) ?? ""
        }
        let kind: ClipKind
        let title: String
        if !fileURLs.isEmpty {
            kind = .file; text = fileURLs.map(\.path).joined(separator: "\n")
            title = fileURLs.map(\.lastPathComponent).joined(separator: ", ")
        } else if types.contains(.png) || types.contains(.tiff) {
            kind = .image; title = "Картинка"
        } else if !text.isEmpty {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            kind = ["https", "http"].contains(URL(string: trimmed)?.scheme?.lowercased() ?? "") && !trimmed.contains(where: \.isWhitespace) ? .link : .text
            title = String(trimmed.replacingOccurrences(of: "\n", with: " ").prefix(240))
        } else {
            kind = .other; title = "Данные: " + (originals.first?.types.first?.rawValue ?? "неизвестный формат")
        }
        return CapturedClip(payload: payload, kind: kind, title: title, text: String(text.prefix(200_000)),
                            source: source, isConcealed: false, isRemote: isRemote)
    }

    private func sourceApplication(for items: [NSPasteboardItem]) -> String {
        let workspace = NSWorkspace.shared
        let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
        var hasDeclaredSource = false
        for item in items {
            guard item.types.contains(sourceType) else { continue }
            hasDeclaredSource = true
            guard let identifier = item.string(forType: sourceType),
                  !identifier.isEmpty,
                  identifier.range(of: "^[A-Za-z0-9][A-Za-z0-9.-]*$", options: .regularExpression) != nil,
                  let url = workspace.urlForApplication(withBundleIdentifier: identifier) else { continue }
            if let name = NSRunningApplication.runningApplications(withBundleIdentifier: identifier).first?.localizedName,
               !name.isEmpty { return Self.visibleSourceName(name) }
            if let bundle = Bundle(url: url) {
                for key in ["CFBundleDisplayName", "CFBundleName"] {
                    if let name = bundle.object(forInfoDictionaryKey: key) as? String, !name.isEmpty { return Self.visibleSourceName(name) }
                }
            }
        }
        // An explicit empty/unknown source means unknown, not the foreground app.
        return hasDeclaredSource ? "" : Self.visibleSourceName(frontmostApplicationName())
    }

    private static func visibleSourceName(_ name: String) -> String {
        ["loginwindow", "windowserver"].contains(name.lowercased()) ? "" : name
    }

    // Only an explicit reveal action should decode a concealed entry for display.
    static func revealedText(_ payload: ClipPayload) -> String? {
        let parts = payload.items.compactMap(text(in:))
        return parts.isEmpty ? nil : parts.joined(separator: "\n")
    }

    /// Plain text and RTF are alternative representations of one clipboard item.
    static func text(in representations: [Representation]) -> String? {
        ClipboardText.decode(representations)
    }

    func restore(_ payload: ClipPayload) throws {
        let items = payload.items.map { representations -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for representation in representations { item.setData(representation.data, forType: .init(representation.type)) }
            return item
        }
        guard !items.isEmpty else { throw ClipboardFailure.writeFailed }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects(items)
        lastChange = pasteboard.changeCount
        guard success else { throw ClipboardFailure.writeFailed }
    }

    static func thumbnail(_ payload: ClipPayload) -> NSImage? {
        for representation in payload.items.joined() where
            [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue].contains(representation.type) {
            guard let source = CGImageSourceCreateWithData(representation.data as CFData, nil),
                  let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceCreateThumbnailWithTransform: true,
                    kCGImageSourceThumbnailMaxPixelSize: 320
                  ] as CFDictionary) else { continue }
            return NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
        }
        return nil
    }

    static func imageData(_ payload: ClipPayload) -> (Data, String)? {
        let reps = payload.items.flatMap { $0 }
        if let png = reps.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue }) { return (png.data, "png") }
        if let tiff = reps.first(where: { $0.type == NSPasteboard.PasteboardType.tiff.rawValue }),
           let bitmap = NSBitmapImageRep(data: tiff.data), let png = bitmap.representation(using: .png, properties: [:]) { return (png, "png") }
        return nil
    }
}
